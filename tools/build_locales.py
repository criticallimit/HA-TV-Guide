"""Generate preloaded frontend and HA translations from registered locale sources."""
import argparse
import json
from hashlib import sha256
from pathlib import Path
from validate_registrations import ROOT, validate


def build(root=ROOT):
    registry=json.loads((root/'languages.json').read_text(encoding='utf-8'))
    locales={code:json.loads((root/'locales'/f'{code}.json').read_text(encoding='utf-8')) for code in registry}
    header='// Generated by tools/build_locales.py; edit languages.json and locales/*.json.\n'
    registry_js=header+'export const languageRegistry = '+json.dumps(registry,ensure_ascii=False,indent=2)+''';
export function normalizeLanguage(value, fallback = 'en') {
  let code = String(value || '').toLowerCase().replaceAll('_', '-');
  while (code) {
    if (Object.hasOwn(languageRegistry, code)) return code;
    const alias = Object.entries(languageRegistry).find(([, item]) => item.aliases?.includes(code));
    if (alias) return alias[0];
    code = code.includes('-') ? code.slice(0, code.lastIndexOf('-')) : '';
  }
  return fallback;
}
'''
    translations=registry_js+'export const translations = '+json.dumps({code:item['messages'] for code,item in locales.items()},ensure_ascii=False,indent=2)+';\n'
    outputs={root/'frontend/app/translations.js':translations.replace('\n','\r\n').encode()}
    outputs[root/'strings.json']=(json.dumps(locales['en']['home_assistant'],ensure_ascii=False,indent=2)+'\n').encode()
    outputs.update({root/'translations'/f'{code}.json':(json.dumps(item['home_assistant'],ensure_ascii=False,indent=2)+'\n').encode() for code,item in locales.items()})
    provenance_path=root/'frontend/app/REFERENCE.json'
    provenance=json.loads(provenance_path.read_text(encoding='utf-8'))
    provenance['bundled_sha256']['translations.js']=sha256(outputs[root/'frontend/app/translations.js']).hexdigest()
    outputs[provenance_path]=(json.dumps(provenance,ensure_ascii=False,indent=2)+'\n').encode()
    return outputs


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    errors=validate()
    if errors:raise SystemExit('\n'.join(errors))
    for path,data in build().items():
        if args.check:
            if not path.exists() or path.read_bytes()!=data:raise SystemExit(f'{path} is stale; run python tools/build_locales.py')
        else:path.write_bytes(data)
    print('Registered frontend and Home Assistant translations are current')
