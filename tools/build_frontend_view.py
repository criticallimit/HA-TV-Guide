"""Bundle the scoped view's HTML and CSS into a preloaded ES module (no runtime fetch)."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / 'custom_components/tv_guide/frontend/app'

def build():
    styles = (ROOT / 'styles.css').read_text()
    styles = styles.replace(':root', '.guide-root')
    styles = re.sub(r'(?m)^html \{', '.guide-root {', styles)
    styles = re.sub(r'(?m)^body \{', '.guide-root {', styles)
    styles = styles.replace('url("fonts/', 'url("/tv_guide/frontend/app/fonts/')
    styles = re.sub(r'@media\s*\((max|min)-width:\s*([^)]*)\)', r'@container tv-guide (\1-width: \2)', styles)
    styles += '''
:host { display:block; width:100%; }
ha-card { display:block; padding:0; margin:0; border:0; box-shadow:none;
  background:var(--primary-background-color); container-type:inline-size; container-name:tv-guide; }
.guide-root { height:100%; overflow:auto; position:relative; font-size:16px; line-height:normal; text-align:left; }
'''
    markup = (ROOT / 'view.html').read_text().strip()
    return '// Generated by tools/build_frontend_view.py; edit view.html and styles.css.\n' + '\n'.join(
        'export const ' + name + ' = ' + json.dumps(value, ensure_ascii=False) + ';'
        for name, value in [('viewMarkup', markup), ('viewStyles', styles)]) + '\n'

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'view-template.js'
    expected=build()
    if args.check:
        if not target.exists() or target.read_text()!=expected:
            raise SystemExit('View bundle is stale; run python tools/build_frontend_view.py')
    else:
        target.write_text(expected)
